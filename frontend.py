import streamlit as st
from pathlib import Path
import re
import traceback
from backend import app


st.set_page_config(
    page_title="Technical Blog Studio",
    page_icon="✍",
    layout="wide",
    initial_sidebar_state="collapsed",
)

st.markdown(
    """
    <style>
        .block-container {max-width: 1120px; padding-top: 2.2rem; padding-bottom: 3rem;}
        .hero {padding: 1.5rem 1.7rem; border: 1px solid rgba(128,128,128,.25);
               border-radius: 16px; margin-bottom: 1.4rem;}
        .muted {color: #777; font-size: .95rem;}
        div[data-testid="stMetric"] {border: 1px solid rgba(128,128,128,.22);
            padding: 12px 14px; border-radius: 12px;}
        .stButton > button {border-radius: 9px; min-height: 2.7rem; font-weight: 600;}
    </style>
    """,
    unsafe_allow_html=True,
)

if "result" not in st.session_state:
    st.session_state.result = None
if "topic" not in st.session_state:
    st.session_state.topic = ""

st.markdown(
    """
    <div class="hero">
        <h1 style="margin:0 0 .35rem 0;">Technical Blog Studio</h1>
        <p class="muted" style="margin:0;">
            Plan, research, and write implementation-focused technical blog posts with LangGraph.
        </p>
    </div>
    """,
    unsafe_allow_html=True,
)

with st.container(border=True):
    st.subheader("Create a blog post")
    topic = st.text_area(
        "What would you like to write about?",
        value=st.session_state.topic,
        placeholder="e.g., Building a RAG application with LangGraph",
        height=110,
        help="Enter a clear topic. The backend will decide whether web research is needed.",
    )

    col1, col2 = st.columns([1, 4])
    with col1:
        generate = st.button("Generate blog", type="primary", use_container_width=True)
    with col2:
        st.caption("The process may take a few minutes because sections are generated by separate workers.")

if generate:
    if not topic.strip():
        st.warning("Enter a topic before generating a blog.")
    else:
        st.session_state.topic = topic.strip()
        initial_state = {
            "topic": topic.strip(),
            "mode": "closed_book",
            "needs_research": False,
            "queries": [],
            "evidence": [],
            "plan": None,
            "sections": [],
            "final": "",
        }
        try:
            # Show live workflow stages as LangGraph nodes finish.
            # Worker nodes run in parallel; each completed worker updates the section count.
            stage_names = [
                "Analyzing topic",
                "Researching",
                "Creating outline",
                "Writing sections",
                "Assembling final blog",
            ]
            stage_state = {name: "Waiting" for name in stage_names}
            stage_state["Analyzing topic"] = "In progress"
            latest_state = dict(initial_state)
            completed_workers = 0
            expected_workers = None

            with st.status("Generating your blog post…", expanded=True) as status:
                stage_area = st.empty()
                live_area = st.empty()

                def render_stages():
                    with stage_area.container():
                        for name in stage_names:
                            state_label = stage_state[name]
                            if state_label == "Complete":
                                marker = "✓"
                            elif state_label == "In progress":
                                marker = "●"
                            elif state_label.startswith("Skipped"):
                                marker = "—"
                            else:
                                marker = "○"
                            st.markdown(f"**{marker} {name}** — {state_label}")

                render_stages()

                for event in app.stream(initial_state, stream_mode="updates"):
                    for node_name, update in event.items():
                        # Keep a usable final state from the streamed node updates.
                        for key, value in update.items():
                            if key == "sections":
                                latest_state.setdefault("sections", [])
                                latest_state["sections"].extend(value or [])
                            else:
                                latest_state[key] = value

                        if node_name == "router":
                            stage_state["Analyzing topic"] = "Complete"
                            if latest_state.get("needs_research"):
                                stage_state["Researching"] = "In progress"
                            else:
                                stage_state["Researching"] = "Skipped — not needed"
                                stage_state["Creating outline"] = "In progress"
                        elif node_name == "research":
                            stage_state["Researching"] = "Complete"
                            stage_state["Creating outline"] = "In progress"
                        elif node_name == "orchestrator":
                            stage_state["Creating outline"] = "Complete"
                            plan = latest_state.get("plan")
                            expected_workers = len(getattr(plan, "tasks", []) or []) if plan else None
                            stage_state["Writing sections"] = "In progress"
                            live_area.info("Writing sections: waiting for section content from the workers…")
                        elif node_name == "worker":
                            completed_workers += 1
                            plan = latest_state.get("plan")
                            expected_workers = expected_workers or (len(getattr(plan, "tasks", []) or []) if plan else None)
                            section_data = update.get("sections", []) or []
                            if section_data:
                                task_id, section_md = section_data[-1]
                                live_area.markdown(f"**Section {task_id} generated**\n\n{section_md}")
                            if expected_workers and completed_workers >= expected_workers:
                                stage_state["Writing sections"] = "Complete"
                                stage_state["Assembling final blog"] = "In progress"
                            else:
                                total = expected_workers if expected_workers is not None else "…"
                                live_area.caption(f"Writing sections: {completed_workers} of {total} sections completed.")
                        elif node_name == "reducer":
                            stage_state["Writing sections"] = "Complete"
                            stage_state["Assembling final blog"] = "Complete"
                            latest_state["final"] = update.get("final", latest_state.get("final", ""))

                        # Keep the stage list refreshed after each node event.
                        stage_area.empty()
                        render_stages()

                st.session_state.result = latest_state
                status.update(label="Blog generation complete", state="complete", expanded=False)
        except Exception as exc:
            st.session_state.result = None
            st.error(f"Blog generation failed: {exc}")
            with st.expander("Technical details"):
                st.code(traceback.format_exc())

result = st.session_state.result

if result:
    plan = result.get("plan")
    final_md = result.get("final", "") or ""
    evidence = result.get("evidence", []) or []
    mode = result.get("mode", "unknown")
    needs_research = result.get("needs_research", False)
    queries = result.get("queries", []) or []

    st.divider()
    st.subheader("Your generated blog")

    m1, m2, m3 = st.columns(3)
    m1.metric("Sections", len(plan.tasks) if plan and getattr(plan, "tasks", None) else 0)
    m2.metric("Research", "Required" if needs_research else "Not required")
    m3.metric("Sources collected", len(evidence))

    tab_blog, tab_outline, tab_sources, tab_details = st.tabs(
        ["Blog preview", "Outline", "Research sources", "Run details"]
    )

    with tab_blog:
        if final_md:
            st.markdown(final_md)
            safe_title = "technical_blog"
            if plan and getattr(plan, "blog_title", None):
                safe_title = re.sub(r'[<>:"/\\|?*]+', "", plan.blog_title).strip()
                safe_title = re.sub(r"\s+", "_", safe_title).lower() or "technical_blog"
            st.download_button(
                "Download Markdown",
                data=final_md.encode("utf-8"),
                file_name=f"{safe_title}.md",
                mime="text/markdown",
                type="primary",
            )
        else:
            st.info("The backend returned no final Markdown content.")

    with tab_outline:
        if plan:
            st.markdown(f"### {plan.blog_title}")
            c1, c2 = st.columns(2)
            c1.write(f"**Audience:** {plan.audience}")
            c2.write(f"**Tone:** {plan.tone}")
            st.write(f"**Blog type:** {plan.blog_kind}")
            if plan.constraints:
                st.write("**Constraints**")
                for constraint in plan.constraints:
                    st.markdown(f"- {constraint}")

            for task in plan.tasks:
                with st.expander(f"{task.id}. {task.title} · {task.target_words} target words"):
                    st.write(task.goal)
                    st.write("**Key points**")
                    for bullet in task.bullets:
                        st.markdown(f"- {bullet}")
                    flags = []
                    if task.requires_research:
                        flags.append("Research")
                    if task.requires_citations:
                        flags.append("Citations")
                    if task.requires_code:
                        flags.append("Code")
                    if flags:
                        st.caption("Requirements: " + " · ".join(flags))
        else:
            st.info("The backend did not return a plan.")

    with tab_sources:
        if evidence:
            for item in evidence:
                title = item.title or item.url
                st.markdown(f"**[{title}]({item.url})**")
                if item.source:
                    st.caption(item.source)
                if item.published_at:
                    st.caption(f"Published: {item.published_at}")
                if item.snippet:
                    st.write(item.snippet)
                st.divider()
        else:
            st.info("No research sources were returned for this topic.")

    with tab_details:
        st.write(f"**Routing mode:** {mode}")
        st.write(f"**Research needed:** {'Yes' if needs_research else 'No'}")
        if queries:
            st.write("**Search queries**")
            for query in queries:
                st.markdown(f"- {query}")
        st.caption("This view shows the routing and research information returned by your backend.")

st.markdown("---")
st.caption("Technical Blog Studio · Powered by LangGraph")
